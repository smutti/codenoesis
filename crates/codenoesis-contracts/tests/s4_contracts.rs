#[test]
fn gt_fr_doc_001_deterministic_markdown() {
    let fixture =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/s4/workspace-docs-v1");
    let semantic: Value = serde_json::from_slice(
        &fs::read(fixture.join("expected-snapshot-semantic.json")).expect("snapshot semantic"),
    )
    .expect("snapshot semantic JSON");
    let generated = generate_documentation_v1(
        &semantic,
        "urn:codenoesis:snapshot:blake3:832888db94f6bf06da375a1cfc055a7c9b80d624b0596a1e45d1f9c646af9b8f",
        "6ed66dd0d5bf2451087fcb17c254048084d9d0f1bd2ea51062d46a38d1defe31",
    )
    .expect("generate reviewed documentation");
    let expected_manifest: Value = serde_json::from_slice(
        &fs::read(fixture.join("expected-documentation-manifest.json"))
            .expect("documentation manifest"),
    )
    .expect("documentation manifest JSON");
    assert_eq!(generated.manifest(), &expected_manifest);
    for document in generated.documents() {
        assert_eq!(
            document.bytes,
            fs::read(fixture.join("expected-docs").join(&document.path))
                .expect("reviewed Markdown"),
            "generated bytes changed for {}",
            document.path
        );
    }
    let bytes = generated
        .documents()
        .iter()
        .map(|document| (document.path.clone(), document.bytes.clone()))
        .collect::<BTreeMap<_, _>>();
    validate_documentation_bundle_v1(
        generated.manifest(),
        &bytes,
        "urn:codenoesis:fixture:s4-workspace-docs-v1",
        "urn:codenoesis:snapshot:blake3:832888db94f6bf06da375a1cfc055a7c9b80d624b0596a1e45d1f9c646af9b8f",
        "6ed66dd0d5bf2451087fcb17c254048084d9d0f1bd2ea51062d46a38d1defe31",
    )
    .expect("validate statement grounding and exact bytes");
}

#[test]
fn e2e_fr_qry_001_exact_id_results() {
    let fixture =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/s4/workspace-docs-v1");
    let semantic = read_json(&fixture.join("expected-snapshot-semantic.json"));
    let manifest = read_json(&fixture.join("expected-documentation-manifest.json"));
    let snapshot_id = "urn:codenoesis:snapshot:blake3:832888db94f6bf06da375a1cfc055a7c9b80d624b0596a1e45d1f9c646af9b8f";
    for (requested_id, expected) in [
        (
            "urn:codenoesis:entity:blake3:18bd97153a41f322136e8f93573877bfc1a2f43fabc6564b789e979a6cffcafa",
            "expected-query-entity.json",
        ),
        (
            "urn:codenoesis:document:blake3:4d6e3c7a3442af14614b515c93197302e23744d004ec671abc4bbab4ae402a99",
            "expected-query-document.json",
        ),
    ] {
        let result = local_query_result_v1(&semantic, &manifest, snapshot_id, requested_id)
            .expect("build reviewed exact-ID query")
            .canonical_stdout()
            .expect("serialize reviewed exact-ID query");
        assert_eq!(
            serde_json::from_slice::<Value>(&result).expect("query result JSON"),
            read_json(&fixture.join(expected))
        );
    }
    for (path, kind) in [
        ("/knowledge_graph/claims/0/id", "claim"),
        ("/knowledge_graph/evidence/0/id", "evidence"),
    ] {
        let requested_id = semantic
            .pointer(path)
            .and_then(Value::as_str)
            .expect("reviewed exact-ID record");
        let result = local_query_result_v1(&semantic, &manifest, snapshot_id, requested_id)
            .expect("query reviewed exact ID")
            .canonical_stdout()
            .expect("serialize exact-ID query");
        assert_eq!(
            serde_json::from_slice::<Value>(&result).expect("query result JSON")["result_kind"],
            kind
        );
    }
    assert!(matches!(
        local_query_result_v1(
            &semantic,
            &manifest,
            snapshot_id,
            "urn:codenoesis:entity:blake3:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        ),
        Err(QueryContractError::NotFound)
    ));
}

